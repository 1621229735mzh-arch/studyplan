import { describe, expect, it } from 'vitest'
import { todayIso } from '@/composables/useFormat'

describe('北京时间9点切换学习日', () => {
  it.each([
    ['2026-10-19T00:00:00+08:00', '2026-10-18'],
    ['2026-10-19T06:00:00+08:00', '2026-10-18'],
    ['2026-10-19T08:59:59.999+08:00', '2026-10-18'],
    ['2026-10-19T09:00:00+08:00', '2026-10-19'],
    ['2026-10-19T09:00:00.001+08:00', '2026-10-19'],
    ['2026-11-01T06:00:00+08:00', '2026-10-31'],
    ['2027-01-01T06:00:00+08:00', '2026-12-31'],
    ['2028-03-01T06:00:00+08:00', '2028-02-29'],
    ['2026-10-18T15:00:00-07:00', '2026-10-18']
  ])('%s 归到 %s', (instant, expected) => {
    expect(todayIso(new Date(instant))).toBe(expected)
  })
})
